"""Pilot report (results/pilot/pilot_report.md): every number the pilot produced, with its source,
the switches that produced it and the limits on what it can show."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .config import as_text


def _f(x, fmt=".2f"):
    try:
        return "–" if x is None or not np.isfinite(float(x)) else format(float(x), fmt)
    except (TypeError, ValueError):
        return "–"


def _pct(x):
    return "–" if x is None or not np.isfinite(float(x)) else f"{100 * float(x):.0f} %"


def write_report(S: dict, cfg, out: Path) -> Path:
    prim = cfg.signal.primary_method
    L = [f"# SAMA pilot report ({S.get('provenance')})", ""]
    if S.get("provenance") == "SYNTHETIC":
        L += ["> **SYNTHETIC DATA.** These sessions were generated by `python -m sama synth-pilot` to test the pipeline. "
              "No number below describes a person. Do not quote it anywhere.", ""]
    L += ["Generated by `python -m sama pilot`. Numbers come from `pilot_summary.json`; window-level rows are in "
          "`pilot_windows.csv`; the configuration used is in `config_used.yaml`.", "",
          "**What this pilot can and cannot show.** It shows whether the recording set-up, synchronisation, compression "
          "ladder and analysis run end to end on real people, and how large the between-person spread is (for the power "
          "re-check). With this many participants it cannot test H1–H5: every interval below is wide, and no p-value is "
          "reported as evidence. Skin tone comes from "
          + {"camera": "the camera with a grey or white card in view, an approximation of the colorimeter the main study will use",
             "measured": "colorimeter readings", "predicted": "a video-to-ITA° model trained on a small sample",
             "monk": "Monk ratings", "none": "nowhere (skin-tone blind run)"}[cfg.ita.source]
          + f". The reference is a {cfg.reference.label}, not ECG; its HRV is pulse-rate variability.", ""]
    F = S["feasibility"]
    P = S["participants"]
    L += ["## 1. Feasibility", "",
          "| Item | Value |", "|---|---|",
          f"| Sessions recorded | {F['n_recorded']} |", f"| Usable after QC | {F['n_usable']} |",
          f"| Synchronisation spread (median / worst session) | {_f(F.get('sync_spread_ms_median'), '.0f')} / {_f(F.get('sync_spread_ms_max'), '.0f')} ms ({', '.join(F.get('sync_method') or [])}) |",
          f"| Session length (median, first to last marker) | {_f(F.get('session_minutes_median'), '.0f')} min |",
          f"| Video length (median) | {_f(F.get('recording_minutes_median'), '.1f')} min |",
          f"| Frames with a face (median) | {_pct(F.get('face_fraction_median'))} |", ""]
    if F["excluded"]:
        L += ["Excluded sessions:", ""] + [f"- {k}: {'; '.join(v)}" for k, v in F["excluded"].items()] + [""]
    L += ["## 2. Participants and skin tone", "",
          f"{P['n']} participants analysed ({P.get('strata_note', '')}); ITA° ({P['ita_source']}) from {_f(P.get('ita_min'), '.1f')}° to {_f(P.get('ita_max'), '.1f')}°; "
          f"Monk {_f(P.get('monk_min'), '.0f')}–{_f(P.get('monk_max'), '.0f')}. Strata by {P['strata_by']}: "
          + ", ".join(f"{k} {v}" for k, v in P["per_stratum"].items()) + ".", ""]
    tone = Path(out) / "pilot_skin_tone.csv"
    if tone.exists():
        t = pd.read_csv(tone)
        L += ["| Participant | Camera ITA° | Flags | Monk | Stratum |", "|---|---|---|---|---|"]
        for r in t.itertuples():
            L.append(f"| {r.participant_id} | {_f(r.ita_camera, '.1f')} | {r.ita_camera_flags if isinstance(r.ita_camera_flags, str) else ''} | {_f(r.monk, '.1f')} | {r.stratum} |")
        L.append("")
    iv = S.get("ita_vs_monk", {})
    L += [f"Camera ITA° vs Monk consensus: Spearman ρ = {_f(iv.get('spearman_rho'))} (95 % CI {_f(iv.get('lo95'))} to {_f(iv.get('hi95'))}, n = {iv.get('n', 0)}); "
          "a strong negative correlation means the two order participants the same way.", ""]
    ra = S.get("raters", {})
    if ra.get("n_raters") == 2 and "kappa_quadratic" in ra:
        L += [f"Two raters: quadratic-weighted κ = {_f(ra['kappa_quadratic'])}, ICC(2,1) = {_f(ra['icc21'])} "
              f"({_f(ra['icc21_lo95'])}–{_f(ra['icc21_hi95'])}), exact {_pct(ra['exact'])}, within one shade {_pct(ra['within_one'])} (n = {ra['n']}).", ""]
    else:
        L += [f"Raters: {ra.get('note', 'not available')}.", ""]
    L += ["## 3. Heart-rate accuracy by method and video level (webcam)", "",
          "| Method | Level | MAE | RMSE | r | Within AAMI | Windows | Participants |", "|---|---|---|---|---|---|---|---|"]
    for m, lv in S["accuracy"].items():
        for lvl, v in sorted(lv.items(), key=lambda kv: (kv[0] != "lossless", kv[0])):
            L.append(f"| {m} | {lvl} | {_f(v['mae'])} | {_f(v['rmse'])} | {_f(v['r'])} | {_pct(v['within_aami'])} | {v['n_windows']} | {v['n_participants']} |")
    L += ["", "AAMI EC13 tolerance: within ±5 bpm or ±10 %, whichever is greater. MAE counts windows without an estimate as failures "
          "(scored against the participant's median estimate); RMSE, r and AAMI use windows with an estimate.", ""]
    if S.get("failures"):
        L += ["Failure rates (method | level | stratum): " + "; ".join(f"{k} {100 * v:.0f} %" for k, v in sorted(S["failures"].items())) + ".", ""]
    st = S["skin_tone"].get(prim, {})
    L += ["## 4. Section 5 results (Figure 6)", "",
          f"**Skin tone (6A).** Change in {prim} MAE per 10° fall in ITA°: {_f(st.get('rise_per_10deg_fall'), '+.2f')} bpm "
          f"(95 % participant-bootstrap CI {_f(st.get('lo95'), '+.2f')} to {_f(st.get('hi95'), '+.2f')}; n = {st.get('n', 0)}); as H1's estimand, "
          f"a ratio of {_f(st.get('ratio_per_10deg_fall'))} per 10° (95 % CI {_f(st.get('ratio_lo95'))} to {_f(st.get('ratio_hi95'))}). "
          f"Between-person SD of MAE {_f(st.get('between_person_sd'))} bpm.", ""]
    L += ["| Method | n | Mean MAE | Change per 10° fall | 95 % CI | Spearman (MAE, Monk) |", "|---|---|---|---|---|---|"]
    for m, v in S["skin_tone"].items():
        L.append(f"| {m} | {v['n']} | {_f(v.get('mae_mean'))} | {_f(v.get('rise_per_10deg_fall'), '+.2f')} | "
                 f"{_f(v.get('lo95'), '+.2f')} to {_f(v.get('hi95'), '+.2f')} | {_f(v.get('spearman_mae_monk'))} |")
    L.append("")
    kb = cfg.pilot.compression_kbps
    L += [f"**Compression (6B).** Penalty = MAE at {kb} kbps minus lossless MAE, per participant, then averaged.", "",
          "| Method | Codec | Stratum | n | Penalty (bpm) | 95 % CI |", "|---|---|---|---|---|---|"]
    for m, cd in S["compression"].items():
        for codec, v in cd.items():
            for sname, b in v["by_stratum"].items():
                L.append(f"| {m} | {codec} | {sname} | {b['n']} | {_f(b['penalty'], '+.2f')} | {_f(b.get('lo95'), '+.2f')} to {_f(b.get('hi95'), '+.2f')} |")
    L.append("")
    L += ["**Agreement (6C).** Bland–Altman, lossless webcam; limits widened for repeated windows per participant (Bland & Altman 2007).", "",
          "| Method | Bias | 95 % limits | SD (clustered / naive) | Windows | Participants |", "|---|---|---|---|---|---|"]
    for m, v in S["agreement"].items():
        if v:
            L.append(f"| {m} | {_f(v['bias'], '+.2f')} | {_f(v['loa_lo'], '+.1f')} to {_f(v['loa_hi'], '+.1f')} | "
                     f"{_f(v.get('sd'))} / {_f(v.get('sd_naive', v.get('sd')))} | {v['n_windows']} | {v['n_participants']} |")
    L.append("")
    for m in ("POS", "SAMA", "CHROM"):
        if (Path(out) / f"figure6_{m}.png").exists():
            L += [f"![Figure 6 ({m})](figure6_{m}.png)", ""]
    if "sama" in S:
        sm = S["sama"]
        L += ["## 5. The SAMA method on the pilot", "",
              f"Bundle `{sm.get('bundle')}`, trained on {', '.join(sm.get('trained_on') or [])}; pilot role: **{sm['pilot_role']}** "
              f"(test_only = no pilot participant was used for training or calibration). Gate: {sm.get('gate_type')}; FiLM conditioning: {sm.get('film')}.", ""]
        cv = sm.get("cv_on_training_data") or {}
        if cv:
            L += [f"Cross-validated on the training data: SAMA MAE {_f(cv.get('mae_sama'))} vs POS {_f(cv.get('mae_pos'))} bpm; "
                  f"gate coverage of shown intervals {_pct(cv.get('coverage_shown'))}, abstention {_pct(cv.get('abstention'))}.", ""]
        for lvl in ("lossless", f"h264_{kb}"):
            v = sm.get(lvl)
            if not v:
                continue
            L += [f"**{lvl}**", "", "| Stratum | Participants | MAE SAMA (all windows) | MAE " + prim + " | Abstention | Coverage (shown) | MAE (shown) | Useful yield |",
                  "|---|---|---|---|---|---|---|---|"]
            for k, b in v.items():
                L.append(f"| {k} | {b['n_participants']} | {_f(b['mae_sama_all'])} | {_f(b.get('mae_primary_all'))} | {_pct(b['abstention'])} | "
                         f"{_pct(b.get('coverage_shown'))} | {_f(b.get('mae_shown'))} | {_pct(b['useful_yield'])} |")
            L.append("")
        L += ["Error on all windows is the fair comparison; error on shown windows falls mechanically as more windows are withheld "
              "(selective-prediction bias), so it is reported only next to the abstention rate.", ""]
        if (Path(out) / "figure_sama_gate.png").exists():
            L += ["![SAMA gate](figure_sama_gate.png)", ""]
    if S.get("hrv"):
        L += ["## 6. HRV (exploratory)", "", f"Reference: {S['hrv'].get('reference_note')}. Windows with motion above "
              f"`quality.motion_warn` = {cfg.quality.motion_warn} are excluded.", "",
              "| Camera method | Blocks | Participants | Windows | RMSSD bias (ms) | 95 % limits | ICC(2,1) of ln RMSSD |", "|---|---|---|---|---|---|---|"]
        for m, v in S["hrv"].items():
            if not isinstance(v, dict) or "ba_rmssd_ms" not in v:
                continue
            b, ic = v["ba_rmssd_ms"], v.get("icc21_ln_rmssd", {})
            L.append(f"| {m} | {v['blocks']} | {v['n_participants']} | {v['n_windows']} | {_f(b.get('bias'), '+.1f')} | "
                     f"{_f(b.get('loa_lo'), '+.0f')} to {_f(b.get('loa_hi'), '+.0f')} | {_f(ic.get('icc'))} ({_f(ic.get('lo95'))}–{_f(ic.get('hi95'))}) |")
        L.append("")
        if (Path(out) / "figure_hrv_ba.png").exists():
            L += ["![HRV](figure_hrv_ba.png)", ""]
    pr = S.get("power_recheck", {})
    L += ["## 7. Power re-check with the pilot's spread", "", pr.get("note", ""), "",
          "| Hypothesis | Spread | Assumed | Pilot (95 % CI) | Power at 36 (pilot) | Power at 45 (pilot) | Power at 45 (upper bound) | Power at 55 (upper bound) |",
          "|---|---|---|---|---|---|---|---|"]
    for h, lab, assumed, key in (("H1", "SD of log MAE around the ITA° trend", 0.55, "pilot_log_sd"), ("H2", "SD of the penalty around the ITA° trend", 1.0, "pilot_sd")):
        v = pr.get(h)
        if v:
            L.append(f"| {h} | {lab} | {assumed} | {_f(v[key])} ({_f(v['sd_ci95'][0])}–{_f(v['sd_ci95'][1])}) | {_f(v['power_36_at_pilot_sd'])} | "
                     f"{_f(v.get('power_45_at_pilot_sd'))} | {_f(v.get('power_45_at_upper_sd'))} | {_f(v.get('power_55_at_upper_sd'))} |")
    if pr.get("H1", {}).get("verdict"):
        L += ["", "H1: " + pr["H1"]["verdict"]]
    L += ["", "## 8. Configuration used", "", "```yaml", as_text(cfg).strip(), "```", ""]
    p = Path(out) / "pilot_report.md"
    p.write_text("\n".join(L))
    return p
